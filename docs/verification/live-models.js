/**
 * index.html against the real models, through OpenRouter: a few steps, to see that each service
 * takes the requests the page sends (the other scripts answer for the models themselves).
 *
 *   1. wave 1 (generate): umr_generate writes one sentence with an OpenAI model, convert loads it
 *   2. sentence wave, step by step: sent_type asks Jev, the next step asks an Anthropic model
 *      (with the skill's tools and final_result), then the same step again with an OpenAI model
 *
 * It costs a little money, so it is not one of the `-test.js` scripts the runner picks up:
 *
 *   OPENROUTER_KEY=sk-or-… npm run test:live            # GENERATE=sol AGENT=haiku OPENAI_AGENT=luna
 *
 * Every request to OpenRouter is printed with its model, tool_choice and status, and the body of
 * one that failed.
 */
const { launchBrowser } = require('./_browser');
const BASE = process.env.BASE || 'http://localhost:8899';
const KEY = process.env.OPENROUTER_KEY;
const GENERATE = process.env.GENERATE || 'sol';
const AGENT = process.env.AGENT || 'haiku';
const OPENAI_AGENT = process.env.OPENAI_AGENT || 'luna';
const SENTENCE = process.env.SENTENCE || 'The boy wants to visit Paris .';

let pass = 0, fail = 0;
const check = (label, ok, extra = '') => {
  (ok ? pass++ : fail++);
  console.log(`  ${ok ? '✓' : '✖'} ${label}${extra ? '\n      ' + extra : ''}`);
};

(async () => {
  if (!KEY) throw new Error('Set OPENROUTER_KEY.');
  const proxy = process.env.HTTPS_PROXY ? [`--proxy-server=${process.env.HTTPS_PROXY}`, '--proxy-bypass-list=localhost;127.0.0.1'] : [];
  const browser = await launchBrowser({ args: proxy });
  const ctx = await browser.newContext({ viewport: { width: 1500, height: 950 }, locale: 'en-US' });
  await ctx.addInitScript((key) => {
    localStorage.setItem('annotator_secrets', JSON.stringify({ apiKeys: { openrouter: key } }));
    localStorage.setItem('skillparse_lang', 'en');
  }, KEY);
  const page = await ctx.newPage();
  const errs = [];
  page.on('pageerror', (e) => errs.push('PAGEERROR: ' + e.message));
  const seen = [];
  page.on('response', async (res) => {
    if (!res.url().startsWith('https://openrouter.ai/api/')) return;
    let body = {};
    try { body = JSON.parse(res.request().postData() || '{}'); } catch { /* not JSON */ }
    const line = { url: res.url().replace('https://openrouter.ai/api/v1/', ''), model: body.model, status: res.status(),
      tools: (body.tools || []).map((t) => t.function?.name), tool_choice: body.tool_choice };
    if (res.status() >= 400) line.error = (await res.text().catch(() => '')).slice(0, 1500);
    seen.push(line);
    console.log('    →', JSON.stringify(line));
  });
  const status = () => page.textContent('#status');
  const settled = () => page.waitForFunction(() => (document.body.dataset.running || '0') === '0', null, { timeout: 240000 });
  const selected = () => page.$eval('.tree li[aria-selected="true"]', (e) => ({
    skill: e.querySelector('.sk')?.textContent, st: e.querySelector('.st')?.textContent, title: e.title || '' })).catch(() => null);
  const stepError = () => page.$eval('#output .error, #output .err', (e) => e.textContent.slice(0, 600)).catch(() => '');
  const importDoc = async (name) => {
    await page.click('#btn-import');
    await page.fill('#modal textarea', SENTENCE);
    await page.fill('#modal input[type=text]', name);
    await page.check('#modal input[value="txt-lines"]');
    await page.click('#modal button:has-text("Import")');
    await page.waitForFunction((n) => document.getElementById('doc').value === n
      && !/loading|Loading/.test(document.getElementById('status').textContent), name, { timeout: 60000 });
  };
  const tree = () => page.$$eval('.tree li', (els) => els.map((e) => `${e.querySelector('.sk')?.textContent}:${e.querySelector('.st')?.textContent}`).join(' '));

  await page.goto(`${BASE}/index.html`);
  await page.waitForFunction(() => document.querySelectorAll('#doc option').length > 0
    && /Ready|ready/.test(document.getElementById('status').textContent), null, { timeout: 180000 });

  // 1. wave 1: one sentence generated by an OpenAI model
  console.log(`\n1. generate with ${GENERATE}`);
  if (!process.env.SKIP_GENERATE) {
  await importDoc('live-generate');
  await page.click('.wave-tab:has-text("generate")');
  await page.waitForTimeout(300);
  await page.selectOption('#model-pick', GENERATE);
  await page.click('#context .items li >> nth=0');
  await settled();
  await page.click('#run-bar .run-first');
  await settled();
  let t = await tree();
  check(`umr_generate answered through final_result (${GENERATE})`, /umr_generate:[◆✓]/.test(t), `${t} · ${await status()} · ${await stepError()}`);
  if (/umr_generate:◆/.test(t)) {
    await page.click('#run-bar .confirm-next:not([disabled])');
    await settled();
    t = await tree();
    check('convert loaded the generated sentence', /convert:[◆✓]/.test(t), `${t} · ${await status()} · ${await stepError()}`);
  }
  }

  // 2. the sentence wave, step by step: Jev, then an agent step with each maker's model
  console.log(`\n2. step by step: Jev, then ${AGENT}, then ${OPENAI_AGENT}`);
  await importDoc('live-steps');
  await page.click('.wave-tab:has-text("sentence")');
  await page.waitForTimeout(300);
  await page.selectOption('#model-pick', AGENT);
  await page.click('#context .items li >> nth=0');
  await settled();
  await page.click('#run-bar .run-first');
  await settled();
  t = await tree();
  check('sent_type was answered by Jev', /sent_type:[◆✓]/.test(t) && seen.some((s) => s.url === 'systemone' && s.status === 200),
    `${t} · ${await status()} · ${await stepError()}`);
  const before = seen.length;
  await page.click('#run-bar .confirm-next:not([disabled])');
  await settled();
  t = await tree();
  const agentStep = await selected();
  const mine = seen.slice(before).filter((s) => s.url === 'chat/completions');
  check(`the next step (${agentStep?.skill}) was answered by ${AGENT}, with tools`,
    mine.length > 0 && mine.every((s) => s.status === 200) && new RegExp(`${agentStep?.skill}:◆`).test(t),
    `${t} · ${await status()} · ${await stepError()}`);

  await page.selectOption('#model-pick', OPENAI_AGENT);
  const before2 = seen.length;
  await page.click('.tab:text-is("Output")').catch(() => {});
  await page.click('#output .review-card button:has-text("Re-run this step")');
  await settled();
  t = await tree();
  const mine2 = seen.slice(before2).filter((s) => s.url === 'chat/completions');
  check(`the same step was answered by ${OPENAI_AGENT}, with tools`,
    mine2.length > 0 && mine2.every((s) => s.status === 200 && /^openai\//.test(s.model)) && new RegExp(`${agentStep?.skill}:◆`).test(t),
    `${t} · ${await status()} · ${await stepError()}`);

  check('no page errors', errs.length === 0, errs.slice(0, 3).join(' | '));
  console.log(`\n${seen.length} requests to OpenRouter · ${pass} passed, ${fail} failed`);
  await browser.close();
  process.exit(fail ? 1 : 0);
})().catch((e) => { console.error(e); process.exit(1); });
